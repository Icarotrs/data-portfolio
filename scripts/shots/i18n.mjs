// Patterns for text that varies (dates, counts…): [regex, pt, es].
const MONTHS = {
  pt: { Jan: "jan", Feb: "fev", Mar: "mar", Apr: "abr", May: "mai", Jun: "jun", Jul: "jul", Aug: "ago", Sep: "set", Oct: "out", Nov: "nov", Dec: "dez" },
  es: { Jan: "ene", Feb: "feb", Mar: "mar", Apr: "abr", May: "may", Jun: "jun", Jul: "jul", Aug: "ago", Sep: "sep", Oct: "oct", Nov: "nov", Dec: "dic" },
};
const RULES = [
  // "Oct 14, 09:12" → "14 out, 09:12"
  [/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2}), (\d\d:\d\d)$/, (m, l) => `${m[2]} ${MONTHS[l][m[1]]}, ${m[3]}`],
  // Axis labels "Jan 17" → "jan 17"
  [/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d\d)$/, (m, l) => `${MONTHS[l][m[1]]} ${m[2]}`],
  // "● 3 days", "▲ 19 days", "12 days"
  [/^([●▲] )?(\d+) days?$/, (m, l) => `${m[1] ?? ""}${m[2]} ${l === "pt" ? "dias" : "días"}`],
  [/^(\d+) d$/, (m) => `${m[1]} d`],
  [/^(\d+) units$/, (m, l) => `${m[1]} ${l === "pt" ? "unidades" : "unidades"}`],
  [/^· (\d+)% neutral$/, (m, l) => `· ${m[1]}% ${l === "pt" ? "neutro" : "neutral"}`],
  // Week labels W27 → S27 (semana)
  [/^W(\d+)$/, (m) => `S${m[1]}`],
];

/** Translate one string (exact match, then patterns); unknown text stays as is. */
export function tr(text, lang) {
  if (lang === "en" || text == null) return text;
  const i = lang === "pt" ? 0 : 1;
  if (WORDS[text]) return WORDS[text][i];
  for (const [re, fn] of RULES) {
    const m = text.match(re);
    if (m) return fn(m, lang);
  }
  return text;
}

/** The table, for use inside the browser (see translateDocument). */
export function table(lang) {
  const i = lang === "pt" ? 0 : 1;
  return Object.fromEntries(Object.entries(WORDS).map(([k, v]) => [k, v[i]]));
}

/**
 * Runs inside the page (passed to Playwright's evaluate, so it must be
 * self-contained): replaces every text node found in `words` or matched by
 * the same patterns as RULES, keeping the surrounding whitespace.
 */
export function translateDocument({ words, lang, months }) {
  const rules = [
    [/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2}), (\d\d:\d\d)$/, (m) => `${m[2]} ${months[m[1]]}, ${m[3]}`],
    [/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d\d)$/, (m) => `${months[m[1]]} ${m[2]}`],
    [/^([●▲] )?(\d+) days?$/, (m) => `${m[1] ?? ""}${m[2]} ${lang === "pt" ? "dias" : "días"}`],
    [/^(\d+) units$/, (m) => `${m[1]} unidades`],
    [/^· (\d+)% neutral$/, (m) => `· ${m[1]}% ${lang === "pt" ? "neutro" : "neutral"}`],
    [/^W(\d+)$/, (m) => `S${m[1]}`],
  ];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    const raw = n.nodeValue;
    const t = raw.replace(/\s+/g, " ").trim();
    if (!t) continue;
    let out = words[t];
    if (out === undefined) {
      for (const [re, fn] of rules) {
        const m = t.match(re);
        if (m) {
          out = fn(m);
          break;
        }
      }
    }
    if (out !== undefined) n.nodeValue = raw.match(/^\s*/)[0] + out + raw.match(/\s*$/)[0];
  }
}

/** Arguments for translateDocument in a given language. */
export const pageArgs = (lang) => ({ words: table(lang), lang, months: MONTHS[lang] });

